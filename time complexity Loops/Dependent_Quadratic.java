public class Dependent_Quadratic {
   public static void main(String[] args) {
        
// A Loop is when the number of iterations of one loop depends on the value of another loop - 


      for(int i = 0 ; i < 10 ; i++){
           for(int j = 0 ;  j < i ; j++){
              System.out.print(i + " ");
           }
      }
   } 
}
